import { C, P, Q, U, W } from '@/data/seed/ids';
import { markAllNotificationsRead, markConversationRead, sendMessage, setNotificationRead } from '@/domain/messages/commands';
import { notificationsFor, unreadConversationCount, unreadCount, unreadNotificationCount } from '@/domain/messages/selectors';
import { submitReview, reviewEligibility } from '@/domain/reviews/commands';
import { aggregateReviews } from '@/domain/reviews/aggregate';
import { submitQuote } from '@/domain/quotes/commands';
import { ctx, expectFail, expectOk, resetIds, seed } from '../helpers';

beforeEach(() => resetIds());

describe('messages and read state', () => {
  it('validates, persists and notifies the other party; opening clears unread for the viewer only', () => {
    let s = seed();
    const owner = ctx(U.meera);
    const contractor = ctx(U.sahyadri);
    expect(unreadCount(s, s.conversations[C.bathroom]!, U.meera)).toBe(1);
    expectFail(sendMessage(s, C.bathroom, '   ', contractor), 'VALIDATION');
    expectFail(sendMessage(s, C.bathroom, 'x'.repeat(2001), contractor), 'VALIDATION');
    expectFail(sendMessage(s, C.bathroom, 'Hello', ctx(U.deccan)), 'FORBIDDEN');

    s = expectOk(sendMessage(s, C.bathroom, 'Grouting starts Monday.', contractor)).state;
    expect(unreadCount(s, s.conversations[C.bathroom]!, U.sahyadri)).toBe(0); // own message
    expect(unreadCount(s, s.conversations[C.bathroom]!, U.meera)).toBe(2);
    const msgNotifs = notificationsFor(s, U.meera).filter((n) => n.link === `/messages/${C.bathroom}` && !n.readAt);
    expect(msgNotifs.length).toBe(2);

    s = expectOk(markConversationRead(s, C.bathroom, owner)).state;
    expect(unreadCount(s, s.conversations[C.bathroom]!, U.meera)).toBe(0);
    expect(notificationsFor(s, U.meera).filter((n) => n.link === `/messages/${C.bathroom}` && !n.readAt)).toHaveLength(0);
    expect(unreadConversationCount(s, U.meera)).toBe(0);
  });

  it('closed enquiries are read-only', () => {
    const s = seed();
    const closed = { ...s, conversations: { ...s.conversations, [C.staircase]: { ...s.conversations[C.staircase]!, closedReason: 'Awarded elsewhere.' } } };
    expectFail(sendMessage(closed, C.staircase, 'Any update?', ctx(U.sahyadri)), 'INVALID_TRANSITION');
  });
});

describe('notifications', () => {
  it('are generated by domain events with deep links, and read state is per recipient', () => {
    let s = seed();
    const before = unreadNotificationCount(s, U.meera);
    const q = s.quotes[Q.terraceGanesh]!;
    s = expectOk(submitQuote(s, Q.terraceGanesh, { ...q.content, validUntil: '2026-11-30', startWindow: { earliest: '2026-11-01', latest: '2026-11-10' }, inclusions: ['Membrane'], exclusions: ['Tiling'] }, ctx(U.ganesh))).state;
    expect(unreadNotificationCount(s, U.meera)).toBe(before + 1);
    const n = notificationsFor(s, U.meera)[0]!;
    expect(n.title).toBe('Revised quote received');
    expect(n.link).toBe(`/owner/projects/${P.terrace}/quotes/${Q.terraceGanesh}`);

    expectFail(setNotificationRead(s, n.id, true, ctx(U.sahyadri)), 'FORBIDDEN');
    s = expectOk(setNotificationRead(s, n.id, true, ctx(U.meera))).state;
    expect(unreadNotificationCount(s, U.meera)).toBe(before);
    s = expectOk(setNotificationRead(s, n.id, false, ctx(U.meera))).state;
    const all = expectOk(markAllNotificationsRead(s, ctx(U.meera)));
    expect(all.value).toBe(before + 1);
    expect(unreadNotificationCount(all.state, U.meera)).toBe(0);
    expect(unreadNotificationCount(all.state, U.sahyadri)).toBeGreaterThan(0);
  });

  it('muted categories are recorded but not counted', () => {
    let s = seed();
    s = { ...s, ownerSettings: { ...s.ownerSettings, [U.meera]: { ...s.ownerSettings[U.meera]!, notificationPrefs: { ...s.ownerSettings[U.meera]!.notificationPrefs, message: false } } } };
    const before = unreadNotificationCount(s, U.meera);
    s = expectOk(sendMessage(s, C.bathroom, 'Muted test', ctx(U.sahyadri))).state;
    expect(unreadNotificationCount(s, U.meera)).toBe(before);
    expect(notificationsFor(s, U.meera)[0]!.muted).toBe(true);
  });
});

describe('reviews', () => {
  it('allows one review per completed project, by its owner only, and updates aggregates', () => {
    let s = seed();
    expect(reviewEligibility(s, W.bathroom, U.meera).ok).toBe(false); // not completed
    expect(reviewEligibility(s, W.plumbing, U.sahyadri).ok).toBe(false); // not the owner
    expect(reviewEligibility(s, W.plumbing, U.meera).ok).toBe(true);
    const input = { rating: 5, communication: 5, quality: 4, scheduleClarity: null, text: 'Neat work and a proper pressure test before closing the walls.' };
    expectFail(submitReview(s, W.plumbing, { ...input, rating: 0 }, ctx(U.meera)), 'VALIDATION');
    expectFail(submitReview(s, W.plumbing, { ...input, text: 'Too short' }, ctx(U.meera)), 'VALIDATION');
    const before = aggregateReviews(Object.values(s.reviews).filter((r) => r.contractorId === U.jal));
    s = expectOk(submitReview(s, W.plumbing, input, ctx(U.meera))).state;
    const after = aggregateReviews(Object.values(s.reviews).filter((r) => r.contractorId === U.jal));
    expect(after.count).toBe(before.count + 1);
    expect(after.average).toBe(4.7);
    expectFail(submitReview(s, W.plumbing, input, ctx(U.meera)), 'CONFLICT');
    expectFail(submitReview(seed(), W.bathroom, input, ctx(U.meera)), 'INVALID_TRANSITION');
  });
});
