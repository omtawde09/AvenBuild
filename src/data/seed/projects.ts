function quote(spec: Partial<Quote> & Pick<Quote, 'id' | 'projectId' | 'contractorId' | 'status' | 'content' | 'createdAt'>): Quote {
  return {
    revision: 1,
    pendingContent: null,
    history: [],
    revisionRequest: null,
    declineReason: null,
    declineNote: '',
    updatedAt: spec.createdAt,
    submittedAt: null,
    viewedAt: null,
    decidedAt: null,
    withdrawnAt: null,
    isSeed: true,
    ...spec,
  };
}

